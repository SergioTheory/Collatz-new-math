# STRONG_RECORDS — только для обучения Markov (без шума)
# ─────────────────────────────────────────────────────────────────────────────
def _is_strong(b: str) -> bool:
    bits = len(b)
    if bits < 71:
        return False
    n = int(b, 2); cur = n; pb = bits; s = 0
    while cur > 1 and s < 500_000:
        cur = cur * 3 + 1 if cur & 1 else cur >> 1
        s += 1
        cb = cur.bit_length()
        if cb > pb: pb = cb
    ratio = pb / bits
    if bits <= 88:
        return ratio >= 1.68   # Zone 2 только (82 бит даёт 1.707, 88 бит ~1.59 граница)
    return ratio >= 1.58       # весь остальной диапазон


STRONG_RECORDS: list[str] = [b for b in PATH_RECORDS_BINARY if _is_strong(b)]


def get_all_as_int() -> list[int]:
    return [int(b, 2) for b in PATH_RECORDS_BINARY]


def get_strong_as_int() -> list[int]:
    return [int(b, 2) for b in STRONG_RECORDS]
