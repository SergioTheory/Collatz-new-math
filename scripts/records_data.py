# Топ-39 сильнейших (≥ 40 бит) — основа для генератора префиксов
def _is_strong(b: str) -> bool:
    """A record is 'strong' (good for Markov training) if it has a high ratio.
    Short records (< 65 bit) are always included regardless of ratio.
    Long records (>= 65 bit) must have ratio >= 1.15 to avoid polluting Markov."""
    if len(b) < 65:
        return len(b) >= 40
    n = int(b, 2); ob = len(b); pb = ob; cur = n; s = 0
    while cur > 1 and s < 500_000:
        cur = cur * 3 + 1 if cur & 1 else cur >> 1; s += 1
        cb = cur.bit_length()
        if cb > pb: pb = cb
    return pb / ob >= 1.15

STRONG_RECORDS: list[str] = [b for b in PATH_RECORDS_BINARY if _is_strong(b)]

def get_all_as_int() -> list[int]:
    """Возвращает все рекорды как Python int."""
    return [int(b, 2) for b in PATH_RECORDS_BINARY]

def get_strong_as_int() -> list[int]:
    """Возвращает только сильные рекорды (40+ бит) как Python int."""
    return [int(b, 2) for b in STRONG_RECORDS]
